def fetch_live_cfb_odds(api_keys):
    if os.path.exists(ODDS_CACHE_FILE):
        file_age = time.time() - os.path.getmtime(ODDS_CACHE_FILE)
        if file_age < CACHE_DURATION_SEC:
            try:
                with open(ODDS_CACHE_FILE, "r") as f:
                    raw_cache = json.load(f)
                    cached = {tuple(json.loads(k)): v for k, v in raw_cache.items()}
                    if len(cached) > 0:
                        return cached
            except Exception:
                pass

    url = "https://api.the-odds-api.com/v4/sports/americanfootball_ncaaf/odds"

    for key in api_keys:
        params = {"apiKey": key, "regions": "us", "markets": "spreads,totals", "oddsFormat": "american"}
        try:
            resp = requests.get(url, params=params, timeout=12)
            if resp.status_code == 200:
                games = resp.json()
                live_market_data = {}
                for g in games:
                    commence_time = g.get("commence_time", "")
                    # Strictly ingest active games scheduled for Saturday's slate
                    if not commence_time.startswith(TARGET_DATE):
                        continue

                    h_raw = g.get("home_team", "")
                    a_raw = g.get("away_team", "")
                    home_team = resolve_clean_name(h_raw)
                    away_team = resolve_clean_name(a_raw)

                    home_spreads, totals = [], []
                    for book in g.get("bookmakers", []):
                        for market in book.get("markets", []):
                            if market.get("key") == "spreads":
                                for out in market.get("outcomes", []):
                                    if out.get("name") == h_raw and out.get("point") is not None:
                                        home_spreads.append(float(out["point"]))
                            elif market.get("key") == "totals":
                                for out in market.get("outcomes", []):
                                    if out.get("name") == "Over" and out.get("point") is not None:
                                        totals.append(float(out["point"]))

                    if home_spreads or totals:
                        live_market_data[(away_team, home_team)] = {
                            "commence_time": commence_time,
                            "market_spread": float(np.median(home_spreads)) if home_spreads else 0.0,
                            "market_total": float(np.median(totals)) if totals else 52.5,
                            "raw_home": h_raw, "raw_away": a_raw
                        }

                if live_market_data:
                    with open(ODDS_CACHE_FILE, "w") as f:
                        json.dump({json.dumps(list(k)): v for k, v in live_market_data.items()}, f)
                    print(f"[✓] Data pulled using API Key ending in: ...{key[-6:]} ({len(live_market_data)} Saturday matchups loaded)")
                    return live_market_data
            else:
                print(f"[!] Key ending in ...{key[-6:]} returned status {resp.status_code}. Rotating to backup key...")
        except Exception as e:
            print(f"[!] Exception on key ...{key[-6:]}: {e}. Cycling key...")

    print("[!] All keys exhausted or connection timed out.")
    return {}

