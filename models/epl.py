def run_syndicate_production_pipeline():
    rolling_ratings = fetch_rolling_team_metrics()
    fixtures = fetch_epl_market_data()
    evaluations = []
    all_executable_bets = []

    for f in fixtures:
        home, away = f["home"], f["away"]
        cons = f["consensus"]

        sim = simulate_match_distribution(home, away, cons["total"]["point"], rolling_ratings)
        p_matrix = sim["prob_matrix"]

        fair_h2h = sim["1x2"]
        h_spread = cons["spread"]["point"]
        fair_spread_h = evaluate_quarter_handicap(p_matrix, h_spread)
        fair_spread_a = 1.0 - fair_spread_h

        tot_pt = cons["total"]["point"]
        fair_tot_o = evaluate_split_total(p_matrix, tot_pt)
        fair_tot_u = 1.0 - fair_tot_o

        unvig_h2h = remove_vig_multiplicative(cons["h2h"])
        unvig_spread = remove_vig_multiplicative({"home": cons["spread"]["home"], "away": cons["spread"]["away"]})
        unvig_total = remove_vig_multiplicative({"over": cons["total"]["over"], "under": cons["total"]["under"]})

        markets = [
            {"mkt": "ML Home", "type": "SIDE", "sel": f"{home} ML", "fair_p": fair_h2h["H"], "unvig_p": unvig_h2h["home"], "odds": cons["h2h"]["home"]},
            {"mkt": "ML Draw", "type": "DRAW", "sel": "Draw ML", "fair_p": fair_h2h["D"], "unvig_p": unvig_h2h["draw"], "odds": cons["h2h"]["draw"]},
            {"mkt": "ML Away", "type": "SIDE", "sel": f"{away} ML", "fair_p": fair_h2h["A"], "unvig_p": unvig_h2h["away"], "odds": cons["h2h"]["away"]},
            {"mkt": f"AH {h_spread:+}", "type": "SIDE", "sel": f"{home} {h_spread:+}", "fair_p": fair_spread_h, "unvig_p": unvig_spread["home"], "odds": cons["spread"]["home"]},
            {"mkt": f"AH {-h_spread:+}", "type": "SIDE", "sel": f"{away} {-h_spread:+}", "fair_p": fair_spread_a, "unvig_p": unvig_spread["away"], "odds": cons["spread"]["away"]},
            {"mkt": f"Total O{tot_pt}", "type": "TOTAL", "sel": f"Over {tot_pt} Goals", "fair_p": fair_tot_o, "unvig_p": unvig_total["over"], "odds": cons["total"]["over"]},
            {"mkt": f"Total U{tot_pt}", "type": "TOTAL", "sel": f"Under {tot_pt} Goals", "fair_p": fair_tot_u, "unvig_p": unvig_total["under"], "odds": cons["total"]["under"]}
        ]

        for cand in markets:
            p = cand["fair_p"]
            d_odds = cand["odds"]
            cand["ev"] = (p * d_odds) - 1.0
            cand["edge"] = p - cand["unvig_p"]
            cand["kelly_pct"] = calculate_kelly(p, d_odds)
            cand["conviction"] = assign_conviction(cand["ev"], cand["edge"], d_odds)
            cand["american_odds"] = decimal_to_american(d_odds)
            cand["american_fair"] = prob_to_american(p)

            if cand["ev"] >= CONFIG["CIRCUIT_BREAKER_EV"]:
                cand["audit_flag"] = "HALT_ANOMALY"
            elif cand["ev"] < CONFIG["MIN_EV_THRESHOLD"]:
                cand["audit_flag"] = "NO_EDGE"
            else:
                cand["audit_flag"] = "PASS"

        # Duplicate Exposure Resolution: Pick highest risk-adjusted edge per category
        side_cands = [c for c in markets if c["type"] == "SIDE" and c["audit_flag"] == "PASS"]
        filtered_side = [sorted(side_cands, key=lambda x: x["kelly_pct"], reverse=True)[0]] if side_cands else []

        total_cands = [c for c in markets if c["type"] == "TOTAL" and c["audit_flag"] == "PASS"]
        filtered_totals = [sorted(total_cands, key=lambda x: x["kelly_pct"], reverse=True)[0]] if total_cands else []

        fixture_bets = filtered_side + filtered_totals
        for b in fixture_bets:
            b["match"] = f"{home} vs {away}"
            b["kickoff"] = f.get("commence_time", "N/A")
            all_executable_bets.append(b)

        evaluations.append({
            "fixture": f,
            "lambda_h": sim["lambda_h"],
            "mu_a": sim["mu_a"],
            "proj_total": sim["proj_total"],
            "all_markets": markets
        })

    # Portfolio Slate Risk Defense: Normalize if aggregate stake exceeds slate cap
    total_unscaled_stake = sum(b["kelly_pct"] for b in all_executable_bets)
    scale_multiplier = 1.0
    if total_unscaled_stake > CONFIG["MAX_SLATE_RISK_PCT"]:
        scale_multiplier = CONFIG["MAX_SLATE_RISK_PCT"] / total_unscaled_stake
        for b in all_executable_bets:
            b["kelly_pct"] *= scale_multiplier

    return evaluations, all_executable_bets, total_unscaled_stake, scale_multiplier

