import os
import requests
import pandas as pd
from dotenv import load_dotenv
from models.nfl_pipeline import generate_nfl_recommendations

load_dotenv()

SUPABASE_URL = os.getenv("SUPABASE_URL", "https://btzzkdjnijzzdqvjnomr.supabase.co").rstrip("/")
SUPABASE_KEY = os.getenv("SUPABASE_KEY")

HEADERS = {
    "apikey": SUPABASE_KEY,
    "Authorization": f"Bearer {SUPABASE_KEY}",
    "Content-Type": "application/json",
    "Prefer": "return=representation"
}

def run_pipeline():
    print("[*] Initiating Syndicate Pipeline Worker...")
    
    # Run exact NFL quantitative engine
    nfl_recs = generate_nfl_recommendations()
    print(f"[✓] Generated {len(nfl_recs)} quantitative NFL model plays.")

    if nfl_recs:
        # Atomic replacement: Clear previous slate & sync new verified model output
        del_res = requests.delete(
            f"{SUPABASE_URL}/rest/v1/bet_recommendations?id=neq.00000000-0000-0000-0000-000000000000",
            headers=HEADERS
        )
        post_res = requests.post(
            f"{SUPABASE_URL}/rest/v1/bet_recommendations",
            headers=HEADERS,
            json=nfl_recs
        )
        print(f"[✓] Synced {len(nfl_recs)} active picks to Supabase (Status: {post_res.status_code}).")
    else:
        print("[!] No qualifying edges generated by model for current slate; preserving existing table.")

if __name__ == "__main__":
    run_pipeline()
